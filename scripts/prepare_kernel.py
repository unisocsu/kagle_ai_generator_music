"""Validate workflow inputs and build the single-file Kaggle script bundle.

Outputs (all under build/):
  kernel/run_music.py            self-contained script uploaded to Kaggle
  kernel/kernel-metadata.json    Kaggle kernel settings
  kernel_ref.txt                 "<owner>/<slug>" used by the status/output steps
  release_notes.md               text for the GitHub Release
"""
import base64
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
KERNEL_BUILD = BUILD / "kernel"
SLUG = "kagle-ai-music-generator"
LANGUAGES = {"en", "he", "es", "fr", "de", "ja", "zh", "unknown"}


def fail(message):
    print(f"::error::{message}")
    raise SystemExit(1)


def number(name, default, minimum, maximum, cast):
    raw = os.environ.get(name, "").strip() or str(default)
    try:
        value = cast(raw)
    except ValueError:
        fail(f"{name} must be a number (got {raw!r})")
    if not minimum <= value <= maximum:
        fail(f"{name} must be between {minimum} and {maximum} (got {value})")
    return value


def main():
    owner = os.environ.get("KAGGLE_USERNAME", "").strip().lower()
    if not owner:
        fail("KAGGLE_USERNAME is empty (secret kagle_user_name).")

    prompt = os.environ.get("IN_PROMPT", "").strip()
    lyrics = os.environ.get("IN_LYRICS", "").strip()
    if not prompt:
        fail("prompt is required.")
    if len(prompt) > 512:
        fail(f"prompt is {len(prompt)} characters; the maximum is 512.")
    if len(lyrics) > 4096:
        fail(f"lyrics are {len(lyrics)} characters; the maximum is 4096.")

    language = os.environ.get("IN_VOCAL_LANGUAGE", "en").strip() or "en"
    if language not in LANGUAGES:
        fail(f"vocal_language must be one of {sorted(LANGUAGES)}.")

    config = {
        "prompt": prompt,
        "lyrics": lyrics,
        "vocal_language": language,
        "instrumental": os.environ.get("IN_INSTRUMENTAL", "false").strip().lower() == "true",
        "duration": number("IN_DURATION", 30, 10, 600, float),
        "num_samples": number("IN_NUM_SAMPLES", 1, 1, 3, int),
        "seed": number("IN_SEED", -1, -1, 2**31 - 1, int),
    }

    template = (ROOT / "kernel" / "run_music.py").read_text(encoding="utf-8")
    engine = (ROOT / "kernel" / "generate.py").read_bytes()
    for token in ("__CONFIG_B64__", "__ENGINE_B64__"):
        if template.count(f'"{token}"') != 1:
            fail(f"Template placeholder {token} must appear exactly once.")

    b64 = lambda raw: base64.b64encode(raw).decode("ascii")
    bundle = (template
              .replace("__CONFIG_B64__", b64(json.dumps(config, ensure_ascii=False).encode("utf-8")))
              .replace("__ENGINE_B64__", b64(engine)))
    header = ("# AUTO-GENERATED by scripts/prepare_kernel.py - edit kernel/run_music.py "
              "and kernel/generate.py instead.\n")

    KERNEL_BUILD.mkdir(parents=True, exist_ok=True)
    (KERNEL_BUILD / "run_music.py").write_text(header + bundle, encoding="utf-8")

    metadata = {
        "id": f"{owner}/{SLUG}",
        "title": "kagle ai music generator",
        "code_file": "run_music.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (KERNEL_BUILD / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    (BUILD / "kernel_ref.txt").write_text(metadata["id"], encoding="utf-8")

    notes = [
        "Generated with ACE-Step 1.5 XL Turbo on Kaggle.", "",
        f"- Prompt: {prompt}",
        f"- Duration: {config['duration']:g}s",
        f"- Vocal language: {language}",
        f"- Instrumental: {config['instrumental']}",
        f"- Versions: {config['num_samples']}",
        f"- Seed: {config['seed']}",
    ]
    (BUILD / "release_notes.md").write_text("\n".join(notes) + "\n", encoding="utf-8")

    print(f"Kernel: {metadata['id']}")
    print(f"Config: {json.dumps({k: v for k, v in config.items() if k != 'lyrics'}, ensure_ascii=False)}")


if __name__ == "__main__":
    main()
