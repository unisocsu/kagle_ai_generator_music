"""Validate inputs and build Kaggle's single-file script bundle.

Kaggle script kernels identify one code_file in kernel-metadata.json.
Therefore this builder combines the maintained engine and entry point into
one uploadable run_music.py, while keeping source modules separate in Git.
"""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "kernel"


def fail(message):
    print(f"::error::{message}")
    raise SystemExit(1)


def number(name, default, minimum, maximum, cast):
    raw = os.environ.get(name, "").strip() or str(default)
    try:
        value = cast(raw)
    except ValueError:
        fail(f"{name} must be numeric")
    if not minimum <= value <= maximum:
        fail(f"{name} must be between {minimum} and {maximum}")
    return value


def main():
    owner = os.environ.get("KAGGLE_USERNAME", "").strip().lower()
    if not owner:
        fail("KAGGLE_USERNAME is empty.")
    prompt = os.environ.get("IN_PROMPT", "").strip()
    lyrics = os.environ.get("IN_LYRICS", "").strip()
    if not prompt:
        fail("prompt is required.")
    if len(prompt) > 512 or len(lyrics) > 4096:
        fail("prompt max 512 chars; lyrics max 4096 chars.")

    config = {
        "prompt": prompt, "lyrics": lyrics,
        "duration": number("IN_DURATION", 30, 10, 600, float),
        "num_samples": number("IN_NUM_SAMPLES", 1, 1, 3, int),
        "seed": number("IN_SEED", -1, -1, 2**31 - 1, int),
        "vocal_language": os.environ.get("IN_VOCAL_LANGUAGE", "en").strip() or "en",
        "instrumental": os.environ.get("IN_INSTRUMENTAL", "false").lower() == "true",
    }

    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "config.json").write_text(
        json.dumps(config, ensure_ascii=False, indent=2), encoding="utf-8")

    engine = (ROOT / "kernel" / "ace_step_engine.py").read_text(encoding="utf-8")
    entry = (ROOT / "kernel" / "run_music.py").read_text(encoding="utf-8")
    entry = entry.replace("from ace_step_engine import generate", "# generate() is defined above in the bundled engine")
    bundled = (
        "# AUTO-GENERATED by scripts/prepare_kernel.py; do not edit in Kaggle.\n"
        "# Source modules: kernel/ace_step_engine.py and kernel/run_music.py\n\n"
        + engine + "\n\n" + entry
    )
    (BUILD / "run_music.py").write_text(bundled, encoding="utf-8")

    metadata = {
        "id": f"{owner}/kagle-ai-music-generator",
        "title": "kagle ai music generator",
        "code_file": "run_music.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (BUILD / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8")
    (ROOT / "build" / "kernel_ref.txt").write_text(metadata["id"], encoding="utf-8")
    print(f"Kernel: {metadata['id']}")
    print("Kaggle upload: one self-contained run_music.py + config.json")
    print("Requested accelerator: NvidiaTeslaT4 (GPU T4 x2)")
    print("Model: ACE-Step 1.5 XL Turbo 4B DiT + 1.7B LM")


if __name__ == "__main__":
    main()
